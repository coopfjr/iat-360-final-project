# Run Batch Evaluation & Output
output_file = "eval_results.md"
print(f"Starting evaluation of {len(test_questions)} questions...")
print(f"Results will be written automatically to '{output_file}'\n")

with open(output_file, "w", encoding="utf-8") as f:
    f.write("# SFU SIAT Course Planner AI - Evaluation Results\n\n")
    f.write(f"**Total Questions Tested:** {len(test_questions)}\n\n")
    f.write("---\n\n")

    for idx, question in enumerate(test_questions, start=1):
        print(f"Processing [{idx}/{len(test_questions)}]: {question[:50]}...")
        start_time = time.time()
        
        try:
            response = qa_chain.invoke({"input": question})
            answer = response['answer']
            sources = set([doc.metadata.get('source', 'Unknown') for doc in response['context']])
            sources_str = ", ".join(sources) if sources else "None"
        except Exception as e:
            answer = f"ERROR: {str(e)}"
            sources_str = "N/A"
            
        elapsed = round(time.time() - start_time, 2)

        f.write(f"### Question {idx}\n")
        f.write(f"**Prompt:** *{question}*\n\n")
        f.write(f"**Response:**\n{answer}\n\n")
        f.write(f"**Sources Referenced:** `{sources_str}`  \n")
        f.write(f"**Latency:** `{elapsed}s` | **Evaluation:** `[ PASS / FAIL ]`  \n\n")
        f.write("---\n\n")
        f.flush()

print(f"\nEvaluation complete. Saved to '{output_file}'.")